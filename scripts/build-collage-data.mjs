import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");

function csv(path) {
  const [head, ...rows] = readFileSync(path, "utf8").trim().split(/\r?\n/);
  const cols = head.split(",");
  return rows.map((row) => {
    const cells = row.split(",");
    return Object.fromEntries(cols.map((col, i) => [col, cells[i] ?? ""]));
  });
}

const apartments = csv(join(root, "public", "apartments-data", "apartments.csv"));
const classified = csv(join(root, "public", "apartments-data", "exposures_classified.csv"));

const apartmentRecords = classified
  .filter((row) => row.category === "apartment")
  .map((row, index) => ({ ...row, pin: apartments[index]?.pin, classCode: apartments[index]?.class }))
  .filter((row) => row.pin);

const embedded = apartmentRecords
  .filter((row) => row.corridor_300 === "0")
  .map((row, index) => ({
    pin: row.pin,
    classCode: row.classCode,
    address: row.address,
    lat: Number(row.lat),
    lon: Number(row.lon),
    dCommercial: Number(row.d_commercial),
    size: 1 + (index % 7 === 0 ? 2 : index % 5 === 0 ? 1 : 0),
  }));

const out = join(root, "app", "generated", "character-collage.ts");
writeFileSync(
  out,
  `// GENERATED by scripts/build-collage-data.mjs from op-mf-proximity data.\n` +
    `// Do not edit by hand.\n` +
    `export const EMBEDDED_APARTMENTS = ${JSON.stringify(embedded)} as const;\n`
);

console.log(`wrote ${out}: ${embedded.length} embedded apartment parcels`);
